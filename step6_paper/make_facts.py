#!/usr/bin/env python3
"""Step 5: turn ../results into LaTeX number macros (facts.tex, leak_facts.tex) and
tables (table_area.tex, table_gap.tex) used by main.tex. Re-run after any experiment
so every number in the paper comes from the data.
Author: Md. Rakib Rayhan
"""
import json, os
import numpy as np
import pandas as pd

H = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(os.path.dirname(H), "results")
T = os.path.join(os.path.dirname(H), "tables")
KEMS = ["ml-kem-512", "ml-kem-768", "ml-kem-1024"]; DSAS = ["ml-dsa-44", "ml-dsa-65", "ml-dsa-87"]
gm = lambda x: float(np.exp(np.log(np.asarray(x, float)).mean()))
F = {}


def f2(x): return f"{x:.2f}"


def main():
    F["NumBuilds"] = str(len(json.load(open(os.path.join(R, "E0_functional_check.json")))))
    p = pd.read_csv(os.path.join(R, "E1_profile.csv"))
    kc = p[p.category == "Keccak-f[1600]"]
    k1 = kc[kc.scheme.isin(KEMS)].share * 100; k2 = kc[kc.scheme.isin(DSAS)].share * 100
    F.update(KeccakShareKemMin=f"{k1.min():.0f}", KeccakShareKemMax=f"{k1.max():.0f}",
             KeccakShareDsaMin=f"{k2.min():.0f}", KeccakShareDsaMax=f"{k2.max():.0f}")
    # DSE
    d = pd.read_csv(os.path.join(R, "E2_dse.csv"), dtype={"mul": str}); d["key"] = d.scheme + d.op
    def g(grp, **kw):
        s = d[d.scheme.isin(grp)]
        for k, v in kw.items(): s = s[s[k] == v]
        return s.set_index("key").cycles
    for nm, grp in [("Kem", KEMS), ("Dsa", DSAS)]:
        it = g(grp, bp="nt", mul="iter", mem="sram"); one = g(grp, bp="nt", mul="1", mem="sram")
        F[f"MulGain{nm}"] = f2(gm(it / one))
        best = max(gm(one / g(grp, bp=b, mul="1", mem="sram")) for b in ["btfn", "bimodal", "gshare"])
        F[f"BpGain{nm}"] = f2(best)
        F[f"CFourLoss{nm}"] = f"{(gm(g(grp, bp='bimodal', mul='1', mem='c4k') / g(grp, bp='bimodal', mul='1', mem='sram')) - 1) * 100:.0f}"
    F["CSixteenLoss"] = f"{max((gm(g(gr, bp='bimodal', mul='1', mem='c16k') / g(gr, bp='bimodal', mul='1', mem='sram')) - 1) * 100 for gr in (KEMS, DSAS)):.0f}"
    # cache
    c = pd.read_csv(os.path.join(R, "E3_cache.csv"))
    ic = c.groupby(["variant", "cache_kb"]).ic_miss.mean() * 100
    F["IcMissBaseTwo"] = f"{ic[('base', 2)]:.0f}"; F["IcMissAllOne"] = f"{ic[('all', 1)]:.1f}"
    F["IcNeedBase"] = str(min(k for k in sorted(c.cache_kb.unique()) if ic[("base", k)] < 1))
    F["IcNeedAll"] = str(min(k for k in sorted(c.cache_kb.unique()) if ic[("all", k)] < 1))
    # extensions
    e = pd.read_csv(os.path.join(R, "E4_extensions.csv")); e = e[e.core == "C1-TB5"]
    base = e[e.variant == "base"].set_index(["scheme", "op"]).cycles
    def sp(v):
        s = e[e.variant == v]
        return [base[(a, o)] / y for a, o, y in zip(s.scheme, s.op, s.cycles)]
    for v, nm in [("all", "All"), ("k", "K"), ("m", "M")]:
        x = sp(v); F[f"{nm}SpeedMin"] = f2(min(x)); F[f"{nm}SpeedMax"] = f2(max(x)); F[f"{nm}SpeedGm"] = f2(gm(x))
    F["KLsSpeed"] = f2(gm(sp("k-ls"))); F["AllLsSpeed"] = f2(gm(sp("all-ls")))
    F["GccSlow"] = f2(1 / gm(sp("base-gccO2"))); F["GccAllSpeed"] = f2(gm(sp("all-gccO2")))
    pm = pd.read_csv(os.path.join(T, "table_baseline_vs_pqm4.csv"))
    r = pm[pm.scheme.isin(KEMS)].ratio_vs_pqm4
    F["PqmRatioMin"] = f2(r.min()); F["PqmRatioMax"] = f2(r.max())
    l = pd.read_csv(os.path.join(R, "E5_unit_latency.csv")); l = l[l.knob == "lat_keccak"]
    l["sp"] = [base[(a, o)] / y for a, o, y in zip(l.scheme, l.op, l.cycles)]
    F["KLatFast"] = f2(gm(l[l.value == l.value.min()].sp)); F["KLatSlow"] = f2(gm(l[l.value == l.value.max()].sp))
    # area
    ap = os.path.join(T, "area_speedup.csv")
    if os.path.exists(ap):
        a2 = pd.read_csv(ap).set_index("variant").area_overhead_pct
        F["AllAreaPct"] = f"{a2['all']:.0f}"; F["AllLsAreaPct"] = f"{a2['all-ls']:.0f}"
    ar = pd.read_csv(os.path.join(R, "E7_area.csv")).set_index("block")["ge"]
    F["LsGE"] = f"{ar[ar.index.str.startswith('pq.keccak-ls')].iloc[0]:,}"
    F["KfGE"] = f"{ar[ar.index.str.startswith('pq.keccak (')].iloc[0]:,}"
    # RTL validation
    vp = os.path.join(R, "V2_rtl_validation.csv")
    if os.path.exists(vp):
        v = pd.read_csv(vp); F["ValRuns"] = str(len(v)); F["ValMaxErr"] = f"{v.error_pct.abs().max():.3f}"
        F["ValAllExact"] = "yes" if v.bit_exact.all() else "no"
    # compilers
    j = json.load(open(os.path.join(R, "E0_functional_check.json")))
    F["GccDivPrefix"] = str(j["ml-kem-768/prefix-gccO2"]["div_instr"]); F["GccDivBase"] = str(j["ml-kem-768/base-gccO2"]["div_instr"])
    with open(os.path.join(H, "facts.tex"), "w") as f:
        f.write("% generated by make_facts.py -- do not edit by hand\n")
        for k, v in F.items():
            f.write(f"\\newcommand{{\\Fact{k}}}{{{v}}}\n")
    print("facts.tex:", len(F), "macros")
    leak_facts(); leak_facts_long(); area_table(); gap_table(); compiler_table()


def leak_facts():
    p = os.path.join(R, "E6_leakage.csv")
    if not os.path.exists(p):
        open(os.path.join(H, "leak_facts.tex"), "w").write("\\item E6 not run yet.\n"); return
    d = pd.read_csv(p); out = []
    for test in d.test.unique():
        s = d[d.test == test]
        for _, r in s[s.leak == 1].groupby(["variant", "hw"]).agg(schemes=("scheme", lambda x: ",".join(sorted(set(x)))),
                                                                  t=("t", lambda x: max((float(v) for v in x), key=abs)), spread=("spread", "max")).reset_index().iterrows():
            out.append(f"\\item {test}: LEAK for variant \\texttt{{{r.variant}}} on \\texttt{{{r.hw}}} ({r.schemes}); "
                       f"max $|t|$={abs(r.t):.1f}, max spread {r.spread} cycles.")
        ok = s.groupby(["variant", "hw"]).leak.max(); n_ok = int((ok == 0).sum())
        out.append(f"\\item {test}: {n_ok} of {len(ok)} (variant, hardware) pairs show no leak at $|t|\\le4.5$ for all three ML-KEM levels.")
    open(os.path.join(H, "leak_facts.tex"), "w").write("\n".join(o.replace("_", "\\_").replace("\\\\_", "\\_") for o in out) + "\n")
    print("leak_facts.tex:", len(out), "items")


def leak_facts_long():
    p = os.path.join(R, "E6c_leakage_long.csv"); out = []
    if os.path.exists(p):
        d = pd.read_csv(p)
        for _, r in d[d.leak == 1].iterrows():
            out.append(f"\\item E6c {r.test}: \\texttt{{{r.variant}}} on \\texttt{{{r.hw}}}: $|t|$={abs(float(r.t)) if str(r.t) != 'inf' else 'inf'}, "
                       f"$\\Delta$mean={r.delta_mean_cycles} cycles, $d$={r.cohen_d}, spread {r.spread} cycles.")
        n = d.groupby(["variant", "hw"]).leak.max()
        out.append(f"\\item E6c: {int((n == 0).sum())} of {len(n)} (code, hardware) pairs show no leak in either test.")
    open(os.path.join(H, "leak_facts_long.tex"), "w").write("\n".join(o.replace("_", "\\_").replace("\\\\_", "\\_") for o in out) + "\n")


def compiler_table():
    j = json.load(open(os.path.join(R, "E0_functional_check.json")))
    order = [("base", "PQClean (current)", "clang", "-O2"), ("Os", "PQClean (current)", "clang", "-Os"),
             ("base-gccO2", "PQClean (current)", "gcc", "-O2"), ("base-gccOs", "PQClean (current)", "gcc", "-Os"),
             ("prefix-clangO2", "pre-2024 (/ q in C)", "clang", "-O2"), ("prefix-clangOs", "pre-2024 (/ q in C)", "clang", "-Os"),
             ("prefix-gccO2", "pre-2024 (/ q in C)", "gcc", "-O2"), ("prefix-gccOs", "pre-2024 (/ q in C)", "gcc", "-Os")]
    with open(os.path.join(T, "table_compiler.tex"), "w") as f:
        f.write("\\begin{tabular}{lllrrr}\\toprule\nSource & Compiler & Opt. & ML-KEM-512 & ML-KEM-768 & ML-KEM-1024 \\\\\\midrule\n")
        for key, src, cc, opt in order:
            vals = [str(j.get(f"{s_}/{key}", {}).get("div_instr", "--")) for s_ in KEMS]
            f.write(f"{src} & {cc} & {opt} & " + " & ".join(vals) + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")


def area_table():
    p = os.path.join(R, "E7_area.csv")
    if not os.path.exists(p): return
    a = pd.read_csv(p)
    with open(os.path.join(T, "table_area.tex"), "w") as f:
        f.write("\\begin{tabular}{lrrrr}\\toprule\nBlock & GE logic (est.) & Flip-flops & LUT4 & RAM bits \\\\\\midrule\n")
        for _, r in a.iterrows():
            rb = int(r.ram_bits) if "ram_bits" in r and r.ram_bits == r.ram_bits else 0
            f.write(f"{r.block.replace('$', '').replace('&', 'and').replace('_', ' ')} & {int(r['ge']):,} & {int(r.ff):,} & {int(r.lut4):,} & {rb:,} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")


